const MIN_SCORE = 4;

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// Основа має стояти на початку слова: «удар» знайде «ударили», але не «наудар»
const toRe = (stem) => new RegExp(`(?<![\\p{L}'’])${escapeRe(stem.trim())}${stem.endsWith(' ') ? '(?![\\p{L}])' : ''}`, 'iu');
const BAD_RES = BAD.map(toRe);
const GOOD_RES = GOOD.map(([stem, weight, topic]) => ({ re: toRe(stem), weight, topic, stem }));

// Повертає { score, topic, matched } для доброї новини або null, якщо вона не підходить
export function scoreNews(title, description = '') {
  const text = `${title} ${description}`.replace(/[’ʼ]/g, "'").toLowerCase();
  if (BAD_RES.some((re) => re.test(text))) return null;
  const byTopic = {};
  const matched = [];
  let score = 0;
  for (const { re, weight, topic, stem } of GOOD_RES) {
    if (!re.test(text)) continue;
    // Слова в заголовку важать удвічі більше, ніж в описі
    const w = re.test(title.toLowerCase().replace(/[’ʼ]/g, "'")) ? weight * 2 : weight;
    score += w;
    matched.push(stem.trim());
    if (topic) byTopic[topic] = (byTopic[topic] || 0) + w;
  }
  const topic = Object.entries(byTopic).sort((a, b) => b[1] - a[1])[0]?.[0];
  if (!topic || score < MIN_SCORE) return null;
  return { score, topic, matched };
}
